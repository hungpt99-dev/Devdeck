use std::env;
use std::fs;
use std::path::PathBuf;

use fluent_syntax::parser::parse;

/// Generate typed message keys from the English source locale. A missing or
/// mistyped key therefore fails to COMPILE, not at runtime in production.
fn main() {
    println!("cargo:rerun-if-changed=../../locales");
    let root = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap()).join("../../locales/en");
    let mut keys: Vec<String> = Vec::new();
    for entry in fs::read_dir(root).expect("locales/en must exist") {
        let path = entry.expect("readable locale entry").path();
        if path.extension().and_then(|e| e.to_str()) != Some("ftl") {
            continue;
        }
        let source = fs::read_to_string(&path).expect("readable .ftl");
        let resource = parse(source.as_str()).expect("valid Fluent source");
        for entry in resource.body {
            if let fluent_syntax::ast::Entry::Message(message) = entry {
                let key = message.id.name;
                if !keys.iter().any(|k| k == key) {
                    keys.push(key.to_string());
                }
            }
        }
    }
    keys.sort();
    let mut generated = String::from(
        "// Generated by i18n/build.rs. Do not edit.\n\
         #[derive(Debug, Clone, Copy, PartialEq, Eq)]\n\
         pub enum MessageKey {\n",
    );
    for key in &keys {
        generated.push_str(&format!("    {},\n", to_pascal(key)));
    }
    generated.push_str(
        "}\n\nimpl MessageKey {\n    pub fn as_str(self) -> &'static str {\n        match self {\n",
    );
    for key in &keys {
        generated.push_str(&format!(
            "            MessageKey::{} => {:?},\n",
            to_pascal(key),
            key
        ));
    }
    generated.push_str("        }\n    }\n}\n\npub const ALL_MESSAGE_KEYS: &[&str] = &[\n");
    for key in &keys {
        generated.push_str(&format!("    {:?},\n", key));
    }
    generated.push_str("];\n");
    let out = PathBuf::from(env::var("OUT_DIR").unwrap()).join("keys.rs");
    fs::write(out, generated).expect("write generated keys");
}

fn to_pascal(key: &str) -> String {
    key.split('-')
        .map(|part| {
            let mut chars = part.chars();
            match chars.next() {
                Some(first) => first.to_uppercase().collect::<String>() + chars.as_str(),
                None => String::new(),
            }
        })
        .collect()
}
